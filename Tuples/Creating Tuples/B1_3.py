my_list = [10, 20, 30, 40]

my_tuple = tuple(my_list)

print("List to Tuple:", my_tuple)
print(type(my_tuple))


numbers = (1, 2, 3, 4)

new_list = list(numbers)

print("Tuple to List:", new_list)
print(type(new_list))

'''List to Tuple: (10, 20, 30, 40)
<class 'tuple'>
Tuple to List: [1, 2, 3, 4]
<class 'list'>'''