# Take two numbers as input (as strings)
num1 = input("Enter the first number: ")
num2 = input("Enter the second number: ")

# Convert the strings to float
a = float(num1)
b = float(num2)

# Perform arithmetic operations
print("Sum =", a + b)
print("Difference =", a - b)
print("Product =", a * b)
print("Quotient =", a / b)