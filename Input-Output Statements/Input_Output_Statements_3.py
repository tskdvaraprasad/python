# Store data
name = "Vara Prasad"
marks = 95

# 1. Comma-separated print()
print("Using comma-separated print():")
print("Name:", name, "Marks:", marks)

# 2. Using str.format()
print("\nUsing str.format():")
print("Name: {} Marks: {}".format(name, marks))

# 3. Using f-strings
print("\nUsing f-strings:")
print(f"Name: {name} Marks: {marks}")

# Using comma-separated print():
# Name: Vara Prasad Marks: 95

# Using str.format():
# Name: Vara Prasad Marks: 95

# Using f-strings:
# Name: Vara Prasad Marks: 95