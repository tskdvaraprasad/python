# Variable
student = "Vara"

# Constant-style name (written in uppercase by convention)
PI = 3.14159

# Function name
def greet():
    return "Hello!"

# Class name
class Student:
    pass

# Name using an underscore
student_age = 18
# Print all of them
print("Variable:", student)
print("Constant-style name:", PI)
print("Function name:", greet())
print("Class name:", Student.__name__)
print("Name using underscore:", student_age)