score = 50
print("Initial score:", score)

score += 10
print("After += 10:", score)

score -= 5
print("After -= 5:", score)

score *= 2
print("After *= 2:", score)

score /= 5
print("After /= 5:", score)

score //= 2
print("After //= 2:", score)

score %= 3
print("After %= 3:", score)

score **= 2
print("After **= 2:", score)

# Initial score: 50
# After += 10: 60
# After -= 5: 55
# After *= 2: 110
# After /= 5: 22.0
# After //= 2: 11.0
# After %= 3: 2.0
# After **= 2: 4.0